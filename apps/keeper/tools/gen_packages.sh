#!/usr/bin/env bash
# Generates PackageList.java from package list files.
# Lines are "package  # comment"; blank and comment-only lines are skipped, duplicates dropped.
# Fails if any name is outside [a-zA-Z0-9_.], so a bad list never reaches the APK.
#
# Usage: tools/gen_packages.sh <output-java-file> [list-file ...]
# Without list files, KEEPER_LISTS is used (space-separated paths, globs allowed); if that is unset too,
# the four core lists lists/sony-bravia-2019/0*.txt of this repo (not optional-extras.txt).
set -euo pipefail

OUT="$1"
shift

if [ $# -gt 0 ]; then
  files=("$@")
elif [ -n "${KEEPER_LISTS:-}" ]; then
  # Unquoted on purpose: split on spaces and expand globs.
  # shellcheck disable=SC2206
  files=($KEEPER_LISTS)
else
  LISTS="$(cd "$(dirname "$0")/../../.." && pwd)/lists/sony-bravia-2019"
  files=("$LISTS"/0*.txt)
fi

for f in "${files[@]}"; do
  if [ ! -f "$f" ] || [ ! -r "$f" ]; then
    echo "package list not found or not readable: $f" >&2
    exit 1
  fi
done

# Only leading/trailing whitespace is trimmed; internal whitespace fails the name check below.
names() {
  sed -e 's/#.*//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' "$@" | grep -v '^$' || true
}
pkgs="$(names "${files[@]}" | awk '!seen[$0]++')"
if [ -z "$pkgs" ]; then
  echo "no package names in: ${files[*]}" >&2
  exit 1
fi
bad="$(grep -v -E '^[a-zA-Z0-9_.]+$' <<<"$pkgs" || true)"
if [ -n "$bad" ]; then
  echo "invalid package name(s) in ${files[*]}:" >&2
  echo "$bad" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo "// Generated by tools/gen_packages.sh from the keeper package lists. Do not edit; rebuild instead."
  echo "package tv.openshelf.keeper.core;"
  echo
  echo "import java.util.Arrays;"
  echo "import java.util.Collections;"
  echo "import java.util.List;"
  echo
  echo "public final class PackageList {"
  echo "    private static final String[] PACKAGES = {"
  while read -r p; do
    echo "            \"$p\","
  done <<<"$pkgs"
  echo "    };"
  echo
  echo "    private PackageList() {"
  echo "    }"
  echo
  echo "    public static List<String> all() {"
  echo "        return Collections.unmodifiableList(Arrays.asList(PACKAGES));"
  echo "    }"
  echo "}"
} > "$OUT"

echo "PackageList: $(grep -c . <<<"$pkgs") packages from ${#files[@]} list file(s):"
for f in "${files[@]}"; do
  echo "  $f ($(names "$f" | grep -c . || true) names)"
done
